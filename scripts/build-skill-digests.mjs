#!/usr/bin/env node
/**
 * Regenerate `src/lib/agents/skill-digests.generated.ts` from the SKILL.md
 * assets under `public/.well-known/agent-skills/`.
 *
 * Why this exists: the Agent Skills Discovery RFC requires each entry in
 * the index to advertise a sha256 of the skill body so agents can verify
 * what they fetched. Computing the digest at request-time meant the
 * Worker had to sub-fetch its own static asset, which is fragile (a
 * single sub-fetch failure took the index down with a 503). Hashing at
 * build time pins the digest to the exact bytes shipped in the bundle —
 * deterministic, no runtime I/O, no KV cache to invalidate.
 *
 * Run automatically as part of `npm run build` (and `npm run dev:worker`).
 * The generated output is checked into git so tests can import it
 * without invoking this script.
 */

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, "..");

const SKILLS = {
  marketplaceSearch: {
    constant: "MARKETPLACE_SEARCH_SHA256",
    source:
      "public/.well-known/agent-skills/marketplace-search/SKILL.md",
  },
};

const OUT_FILE = join(repoRoot, "src/lib/agents/skill-digests.generated.ts");

const lines = [];
lines.push("/**");
lines.push(" * Auto-generated by scripts/build-skill-digests.mjs.");
lines.push(" *");
lines.push(" * SHA-256 digests of the SKILL.md assets advertised by");
lines.push(" * /.well-known/agent-skills/index.json. Regenerate by running");
lines.push(" * `npm run build` (or `node scripts/build-skill-digests.mjs`)");
lines.push(" * after editing any SKILL.md.");
lines.push(" */");
lines.push("");

for (const { constant, source } of Object.values(SKILLS)) {
  const bytes = readFileSync(join(repoRoot, source));
  const sha = createHash("sha256").update(bytes).digest("hex");
  lines.push(`// Source: ${source} (${bytes.length} bytes)`);
  lines.push(`export const ${constant} = ${JSON.stringify(sha)};`);
  lines.push("");
}

writeFileSync(OUT_FILE, lines.join("\n"));
console.log(`Wrote ${OUT_FILE}`);
